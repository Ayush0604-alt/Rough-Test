"""The input gate.

One question blocks: is there anything here worth generating tests from? Everything else is a
warning, because a thin input should still produce an honest thin suite rather than nothing — the
same posture the requirements pack takes toward a repository with little in it.

Deterministic, like every gate in this system. A gate that could be reasoned past is not a gate.
"""

from __future__ import annotations

from collections import Counter

from agentic.capabilities.registry import (
    CapabilityContext,
    CapabilityResult,
    capability,
)
from agentic.schemas.core import GateReport, Severity, ValidationIssue
from agentic.schemas.testgen import Band, QualifiedSet, RequirementSet

# Above this share of the input excluded, the artifact probably is not what the operator meant to
# point at. A warning, never a block: a set of mostly-rejected requirements is a real thing to
# report on.
HIGH_EXCLUSION_SHARE = 0.5


def _issue(code: str, severity: Severity, message: str, subject: str = "") -> ValidationIssue:
    return ValidationIssue(code=code, severity=severity, message=message, subject_id=subject or None)


@capability("validate_requirement_input")
def validate_requirement_input(ctx: CapabilityContext) -> CapabilityResult:
    """Check the qualified input is worth proceeding on, and say what is wrong with it."""
    qualified = ctx.load("qualified_set", QualifiedSet)
    requirement_set = ctx.load("requirement_set", RequirementSet)

    issues: list[ValidationIssue] = []
    checks = 0

    records = qualified.records
    counts = Counter(record.band.value for record in records)
    testable = [record for record in records if record.testable]

    # --- the one blocking check ---------------------------------------------------------------
    checks += 1
    if not testable:
        issues.append(
            _issue(
                "NO_TESTABLE_REQUIREMENTS",
                Severity.ERROR,
                f"None of the {len(records)} requirement(s) qualified for test generation "
                f"({', '.join(f'{c} {b}' for b, c in sorted(counts.items())) or 'none banded'}). "
                "Proceeding would mean inventing tests rather than deriving them.",
            )
        )

    # --- everything below is reported, never blocking -----------------------------------------
    checks += 1
    if requirement_set.read_issues:
        by_code = Counter(issue.code for issue in requirement_set.read_issues)
        issues.append(
            _issue(
                "INPUT_READ_ISSUES",
                Severity.WARNING,
                f"{len(requirement_set.read_issues)} entr(y/ies) needed defensive handling: "
                + ", ".join(f"{code} ({count})" for code, count in by_code.most_common())
                + ". Each is recorded with its position in the input file.",
            )
        )

    checks += 1
    excluded = counts.get(Band.EXCLUDED.value, 0)
    if records and excluded / len(records) > HIGH_EXCLUSION_SHARE:
        issues.append(
            _issue(
                "HIGH_EXCLUSION_RATE",
                Severity.WARNING,
                f"{excluded} of {len(records)} requirement(s) were excluded from test generation. "
                "Check the artifact is the one you meant to point at.",
            )
        )

    checks += 1
    needs_clarification = counts.get(Band.NEEDS_CLARIFICATION.value, 0)
    if needs_clarification:
        issues.append(
            _issue(
                "REQUIREMENTS_NEED_CLARIFICATION",
                Severity.WARNING,
                f"{needs_clarification} requirement(s) state no observable outcome and carry no "
                "usable acceptance criterion. Each yields a question rather than a test.",
            )
        )

    checks += 1
    assumed = counts.get(Band.ELIGIBLE_WITH_ASSUMPTIONS.value, 0)
    if testable and assumed / len(testable) > HIGH_EXCLUSION_SHARE:
        issues.append(
            _issue(
                "MOSTLY_ASSUMED_DERIVATION",
                Severity.WARNING,
                f"{assumed} of {len(testable)} testable requirement(s) can only be tested under a "
                "stated assumption, usually because no usable acceptance criterion survived. "
                "Expect a suite that needs review before automation.",
            )
        )

    checks += 1
    discarded = sum(len(record.discarded_criteria) for record in records)
    if discarded:
        issues.append(
            _issue(
                "GENERATED_CRITERIA_DISCARDED",
                Severity.WARNING,
                f"{discarded} acceptance criterion/criteria were generated by the requirements "
                "pack rather than read off the evidence, and were discarded. A test derived from "
                "one would assert nothing.",
            )
        )

    checks += 1
    if requirement_set.missing_contract_keys:
        issues.append(
            _issue(
                "OLDER_CONTRACT",
                Severity.WARNING,
                "The artifact predates the current requirements-pack contract and is missing "
                f"{', '.join(requirement_set.missing_contract_keys)}. Defaults were used; "
                "grouping quality may be lower than for a current artifact.",
            )
        )

    report = GateReport.from_issues(
        "input_gate",
        issues,
        checks,
        metrics={
            "requirements": len(records),
            "testable": len(testable),
            "bands": dict(counts),
            "discarded_criteria": discarded,
        },
    )
    return CapabilityResult(
        gate=report,
        artifacts={"input_gate": report},
        metrics={"input_gate_valid": report.valid, "input_gate_warnings": report.warnings},
    )
